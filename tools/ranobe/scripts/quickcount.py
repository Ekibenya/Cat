# -*- coding: utf-8 -*-
"""開局を書いている最中の速報カウンタ。measure.py が落ちる前に自分で見る用。

    python3 quickcount.py <稿.md> [...]

measure.py と同じ正規表現を使う。合否は出さない——数だけ出す。
「あと罵倒が三つ足りない」を書きながら知るための道具であって、採点器ではない。
"""
import io
import re
import sys

PATS = {
    '罵倒C20>=8': r'他妈的|妈的|他娘的|滚|闭嘴|贱|狗东西|狗崽子|狗屎|杂种|崽子|放屁|'
                  r'死小子|臭小子|王八|操|畜生|蠢货|婊|傻|白痴|废物|去死|神经病|疯子|见鬼|'
                  r'混蛋|该死|要命|屁话|屎',
    '感嘆詞C13>=3': r'呜哇|哎呀|哎哟|唉|呃+|啊啊|诶+|哇+|嘿嘿|嘻嘻|哈哈|噗|哼|嘛[，。、]|唔+|呼+|嗯+',
    '確認C14>=2': r'对吧|是吧|不是吗|知道吗|好吗|是不是|吧？|吗。|了吧|没有吗|行吗',
    '聴覚C18>=8': r'声|响|叫|喊|嚎|咔|嘎|噗|哗|咚|嘶|吼|静|听',
    '感嘆符C21>=10': r'！',
    '内心C3>=8': r'（[^）]+）',
    '絶叫C2>=2': r'【[^】]+】',
    '加害C23>=2': r'抢|夺|剥下|扒下|扒了|归我|是我的了|分了|值几|值多少|卖多少|能卖|能换|'
                 r'换多少|赔率|押|赌|战利|摸尸|翻他|搜身|拿走|顺手|好玩|有意思|看热闹|'
                 r'叫人来看|脱下来|脱了|拧下|捡走|收进怀里|几头|几张羊皮|几匹绢|一头能|'
                 r'卖两次|卖给|涨价|太少了',
    '見下しC24>=1': r'这帮|那帮|这些东西|这东西|牲口|不算人|奴才|贱民|杂碎|一群|狗一样|畜生一样',
    '陰険C25>=1': r'嫁祸|栽赃|推给|算在|报上去|告发|密告|骗|装作|假装|学了一下|拿捏|把柄|'
                 r'涨价|没人看见|只有我知道|其实我|一步都没|跟我没关系|就这么写|卖两次',
    '訳語連接': r'其实|当然|不过|毕竟|明明|反正|总之|果然|难道|究竟|确实|甚至|居然|竟|'
              r'原本|原来|看来|似乎|大概|恐怕|说不定|不如|即使|即便|虽然|然而|于是|'
              r'因此|这么|那么|根本|分明',
}
SMELL = r'味|臭|腥|膻|焦|馊|酸|骚|香|嗅|闻(?!言)|鼻子'
ONOMA = r'[咔哗啪轰砰嗒锵咚叮噼铛嘟咕沙嘶哐吱]'


def main(paths):
    for p in paths:
        raw = io.open(p, encoding='utf-8').read()
        body = raw.split('<mvu_panel>')[0]
        ps = [x.strip() for x in body.split('\n') if x.strip()]
        print('■', p)
        for k, v in PATS.items():
            n = len(re.findall(v, body))
            print('   %-14s %d' % (k, n))
        print('   %-14s %d種' % ('嗅覚C17>=2', len(set(re.findall(SMELL, body)))))
        ok = any(re.fullmatch(r'[^。！？「」（）【】]{1,6}[。！]', x) and re.search(ONOMA, x)
                 for x in ps)
        print('   %-14s %s' % ('擬音行C4', 'OK' if ok else '無い'))
        mad = {
            '数えている': bool(re.search(r'第[〇一二三四五六七八九十百千两0-9]+(次|遍|回|趟|个)'
                                     r'|我数(着|过|了)|数到|一天三遍|加起来大概有', body)),
            '場違いな笑い': bool(re.search(r'笑(了出来|出声|得|出来|了一下|了一声)'
                                      r'|忍不住笑|想笑|可笑|滑稽|在笑|笑了。', body)),
            '自白': bool(re.search(r'其实我|说实话|老实说|我承认|不想承认|不肯承认|说来丢人', body)),
            '絶叫の発作': len(re.findall(r'【[^】]+】', body)) >= 4,
        }
        cores = []
        for x in ps:
            c = re.sub(r'^[（(【「『]+|[）)】」』]+$', '', x.strip())
            c = re.sub(r'^[…\.．\s]+', '', c)
            c = re.sub(r'[啊呀吧呢了嘛哦噢的]*[。！？…\.]*$', '', c)
            if 2 <= len(c) <= 12:
                cores.append(c)
        mad['同語反復'] = any(cores.count(c) >= 2 for c in set(cores))
        print('   %-14s %d（%s）' % ('狂気C11>=3', sum(mad.values()),
                                   '/'.join(k for k, v in mad.items() if v) or '無'))


if __name__ == '__main__':
    main(sys.argv[1:])
