# 误伤豁免：这些词组里出现上面的字串是对的，不算。
EXEMPT = [
    '大人物', '大人家', '城大人多', '主大人易政',   # 「大人」在文言里本指长辈、大人物，只有作面称才错
    '丞相', '相国',
    '缠足对她们',                                  # 卡里这一句是在说它不成立
]

# 「秦没有纸」「无砂糖」这一路是考据，正是要写的，不算穿帮。
NEG_RX = re.compile(r'(没有|没|无|未见|不见|不用|不许|绝不)[一-鿿、／/】【（）()]{0,30}$')
NEG_AFT_RX = re.compile(r'^[一-鿿、／/】【（）()]{0,12}(都没有|没有|都不许|不许|一个都不)')

# 禁用表自己要把禁用词写出来才说得清。判断按「这个词所在的那一句」来，不按固定字窗——
# 「禁江湖、武林、内功、轻功、点穴。」这种长列表，末尾几个词离「禁」字早就超过十几个字了。
META_RX = re.compile(r'禁|不许|不用|写作|改成|改用|一律用|这一路|之类|路后世|即改')
SENT_RX = re.compile(r'[^。！？；\n]*')


def _sentence_at(t, i):
    a = max(t.rfind('。', 0, i), t.rfind('\n', 0, i), t.rfind('；', 0, i),
            t.rfind('！', 0, i), t.rfind('？', 0, i)) + 1
    m = SENT_RX.match(t, i)
    return t[a:m.end() if m else i]


def scan(text, where=''):
    hits = []
    t = text
    for ex in EXEMPT:
        t = t.replace(ex, '　' * len(ex))
    for word, alt, why in BAN:
        for m in re.finditer(re.escape(word), t):
            if META_RX.search(_sentence_at(t, m.start())):   # 讲规矩，不是在用
                continue
            head = t[max(0, m.start() - 40):m.start()]
            if NEG_RX.search(head) or NEG_AFT_RX.search(t[m.end():m.end() + 20]):
                continue                                     # 在说「没有它」
            a = max(0, m.start() - 14)
            ctx = t[a:m.end() + 14]
            hits.append((word, alt, why, ctx.replace('\n', ' ')))
    return hits


def main(argv):
    if argv and argv[0] == '--text':
        hits = scan(argv[1])
        for w, alt, why, ctx in hits:
            print('  × %-8s（%s）→ %s\n      …%s…' % (w, why, alt, ctx))
        print('=>', '干净' if not hits else '%d 处串朝代' % len(hits))
        return 1 if hits else 0

    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'st', 'data')
    total = 0
    for p in sorted(glob.glob(os.path.join(root, 'openings', '*.md'))):
        h = scan(io.open(p, encoding='utf-8').read())
        if h:
            total += len(h)
            print('■ %s' % os.path.basename(p))
            for w, alt, why, ctx in h:
                print('  × %-8s（%s）→ %s   …%s…' % (w, why, alt, ctx))
    for p in sorted(glob.glob(os.path.join(root, 'lore', '*.json'))):
        for e in json.load(io.open(p, encoding='utf-8')):
            h = scan(e.get('content', '') + e.get('title', ''))
            if h:
                total += len(h)
                print('■ %s :: %s' % (os.path.basename(p), e.get('title', '')[:24]))
                for w, alt, why, ctx in h:
                    print('  × %-8s（%s）→ %s   …%s…' % (w, why, alt, ctx))
    mp = os.path.join(root, 'meta.json')
    if os.path.isfile(mp):
        m = json.load(io.open(mp, encoding='utf-8'))
        for k in ('description', 'personality', 'scenario',
                  'system_prompt', 'post_history_instructions'):
            h = scan(str(m.get(k) or ''))
            if h:
                total += len(h)
                print('■ meta.json :: %s' % k)
                for w, alt, why, ctx in h:
                    print('  × %-8s（%s）→ %s   …%s…' % (w, why, alt, ctx))
    print('\n禁用词 %d 条 / 串朝代 %d 处' % (len(BAN), total))
    return 0 if total == 0 else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
