def _e(era, name, lines, keys, cat_rule):
    e = ERAS[era]
    head = '〔%s · %s〕' % (yl(e['y']), e.get('t', ''))
    body = list(lines) + RULE[cat_rule]
    return {'title': head + name, 'cat': '%s %s' % (yl(e['y']), e.get('t', '')),
            'keys': keys, 'src': 'ERA%02d' % era, 'era': era,
            'content': NL.join('· ' + x for x in body)}


